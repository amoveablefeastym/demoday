import type { Action, DemoPlan, Target } from "./schema.ts";
import { VIEWPORT } from "./probe.ts";

const q = (s: string) => JSON.stringify(s);

export function locatorCode(t: Target): string {
  if (t.id) return `page.getByTestId(${q(t.id)}).first()`;
  if (t.role) return `page.getByRole(${q(t.role)}${t.name ? `, { name: ${q(t.name)} }` : ""}).first()`;
  if (t.label) return `page.getByLabel(${q(t.label)}).first()`;
  if (t.placeholder) return `page.getByPlaceholder(${q(t.placeholder)}).first()`;
  if (t.text) return `page.getByText(${q(t.text)}).first()`;
  if (t.css) return `page.locator(${q(t.css)}).first()`;
  throw new Error(`Target has no selector: ${JSON.stringify(t)}`);
}

function actionCode(a: Action, i: number): string {
  const meta = `{ kind: ${q(a.kind)}, caption: ${q(a.caption)}, emphasis: ${a.emphasis} }`;
  const hold = a.emphasis ? 2600 : 1100;
  const needsTarget = a.kind === "click" || a.kind === "hover" || (a.kind === "fill" && !!a.target);
  if (needsTarget && !a.target) throw new Error(`Action #${i} (${a.kind}) needs a target`);
  const loc = needsTarget ? locatorCode(a.target!) : "";
  let body: string;
  switch (a.kind) {
    case "goto":
      body = `await page.goto(${q(a.value ?? "")}, { waitUntil: "load" });
    await page.waitForLoadState("networkidle", { timeout: 8000 }).catch(() => {});
    await page.waitForTimeout(900);`;
      break;
    case "click":
      body = `const el = ${loc};
    const box = await aim(el);
    ev.box = box;
    await click(el);
    await page.waitForTimeout(${hold});`;
      break;
    case "fill":
      if (!a.target) {
        body = `const fb = await page.locator(":focus").first().boundingBox({ timeout: 300 }).catch(() => null);
    if (fb) ev.box = { x: fb.x, y: fb.y, w: fb.width, h: Math.min(fb.height, 260) };
    await type(page.locator(":focus"), ${q(a.value ?? "")});
    await page.waitForTimeout(${hold});`;
        break;
      }
      body = `const el = ${loc};
    ev.box = await aim(el);
    await click(el);
    await type(el, ${q(a.value ?? "")});
    await page.waitForTimeout(${hold});`;
      break;
    case "hover":
      body = `ev.box = await aim(${loc});
    await page.waitForTimeout(${hold});`;
      break;
    case "press":
      body = `const fb = await page.locator(":focus").first().boundingBox({ timeout: 300 }).catch(() => null);
    if (fb) ev.box = { x: fb.x, y: fb.y, w: fb.width, h: Math.min(fb.height, 260) };
    await page.keyboard.press(${q(a.value ?? "Enter")});
    await page.waitForTimeout(${hold});`;
      break;
    case "scroll":
      body = `for (let s = 0; s < 20; s++) { await page.mouse.wheel(0, ${Number(a.value ?? 600)} / 20); await page.waitForTimeout(25); }
    await page.waitForTimeout(600);`;
      break;
    case "wait":
      body = `await page.waitForTimeout(${Number(a.value ?? 1000)});`;
      break;
  }
  return `  // ${i}. ${a.kind}${a.caption ? ` — "${a.caption}"` : ""}
  await step(${i}, ${meta}, async (ev) => {
    ${body}
  });`;
}

/** Emit a standalone, editable Playwright script. Run: npx tsx record.ts <outDir> */
export function generateScript(plan: DemoPlan): string {
  return `// Generated by demoday for ${plan.product.name}. Edit freely, then re-run:
//   npx tsx record.ts <outDir>
// Writes <outDir>/raw.webm and <outDir>/events.json (timings + boxes + cursor path).
import { chromium, type Locator } from "playwright";
import { mkdirSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const OUT = process.argv[2] ?? "out";
const HEADED = process.argv.includes("--headed");
const W = ${VIEWPORT.width}, H = ${VIEWPORT.height};
mkdirSync(OUT, { recursive: true });

const browser = await chromium.launch({ headless: !HEADED });
const context = await browser.newContext({
  viewport: { width: W, height: H },
  recordVideo: { dir: join(OUT, ".video"), size: { width: W, height: H } },
  permissions: ["clipboard-read", "clipboard-write"],
  colorScheme: "light",
});
const page = await context.newPage();
const t0 = Date.now(); // video clock starts with the page
const now = () => (Date.now() - t0) / 1000;

type Box = { x: number; y: number; w: number; h: number };
const events: any[] = [];
const cursor: { t: number; x: number; y: number; click?: boolean }[] = [];
const failures: { index: number; error: string; aria: string }[] = [];
let mouse = { x: W * 0.62, y: H * 0.7 };
cursor.push({ t: 0, ...mouse });

const ease = (k: number) => (k < 0.5 ? 4 * k * k * k : 1 - Math.pow(-2 * k + 2, 3) / 2);

/** Human-paced cursor glide; Remotion redraws the cursor from these keyframes. */
async function glide(x: number, y: number) {
  const from = { ...mouse };
  const dist = Math.hypot(x - from.x, y - from.y);
  const n = Math.max(12, Math.min(40, Math.round(dist / 22)));
  cursor.push({ t: now(), ...from });
  for (let i = 1; i <= n; i++) {
    const k = ease(i / n);
    await page.mouse.move(from.x + (x - from.x) * k, from.y + (y - from.y) * k);
    await page.waitForTimeout(14);
  }
  mouse = { x, y };
  cursor.push({ t: now(), x, y });
}

/** Elements that are attached but not "visible" (e.g. the hidden textarea inside Monaco/CodeMirror)
 *  are aimed at via their nearest visible ancestor and clicked with the real mouse. */
const proxied = new WeakSet<Locator>();
async function aim(el: Locator): Promise<Box> {
  let b: { x: number; y: number; width: number; height: number } | null = null;
  await el.waitFor({ state: "attached", timeout: 12000 });
  try {
    await el.waitFor({ state: "visible", timeout: 1200 });
    await el.scrollIntoViewIfNeeded();
    b = await el.boundingBox();
  } catch {
    b = await el.evaluate((n) => {
      for (let p: Element | null = n; p; p = p.parentElement) {
        const r = p.getBoundingClientRect();
        if (r.width > 60 && r.height > 30) return { x: r.x, y: r.y, width: r.width, height: r.height };
      }
      return null;
    });
    if (!b) throw new Error("element is not visible and has no visible container");
    proxied.add(el);
  }
  b = b!;
  const tall = b.height > 120; // big targets (editors, canvases): aim near the top-left, where text goes
  const x = tall ? b.x + Math.min(b.width * 0.3, 220) : b.x + b.width / 2;
  const y = tall ? b.y + Math.min(b.height * 0.15, 90) : b.y + b.height / 2;
  await glide(x, y);
  await page.waitForTimeout(160);
  return { x: b.x, y: b.y, w: b.width, h: tall ? Math.min(b.height, 260) : b.height };
}

async function click(el: Locator) {
  cursor.push({ t: now(), ...mouse, click: true });
  if (proxied.has(el)) await page.mouse.click(mouse.x, mouse.y);
  else await el.click();
}

/** Visible typing for short strings; a real paste for big payloads (works in code editors too). */
async function type(el: Locator, text: string) {
  await page.keyboard.press("ControlOrMeta+A");
  if (text.length > 80) {
    await page.evaluate((t) => navigator.clipboard.writeText(t), text);
    await page.keyboard.press("ControlOrMeta+V");
  } else {
    await page.keyboard.type(text, { delay: Math.max(18, Math.min(55, 2600 / Math.max(1, text.length))) });
  }
}

async function step(index: number, meta: { kind: string; caption: string; emphasis: boolean }, fn: (ev: any) => Promise<void>) {
  const ev: any = { index, ...meta, t: now() };
  try {
    await fn(ev);
    ev.end = now();
    events.push(ev);
    console.log(\`  ✓ \${index} \${meta.kind} \${meta.caption}\`);
  } catch (e: any) {
    const error = String(e?.message ?? e).split("\\n")[0];
    const aria = await page.locator("body").ariaSnapshot().catch(() => "");
    failures.push({ index, error, aria });
    console.log(\`  ✗ \${index} \${meta.kind}: \${error}\`);
  }
}

${plan.newWay.actions.map(actionCode).join("\n\n")}

await page.waitForTimeout(800);
const endT = now();
const video = page.video()!;
await context.close();
renameSync(await video.path(), join(OUT, "raw.webm"));
await browser.close();
writeFileSync(join(OUT, "events.json"), JSON.stringify({ width: W, height: H, end: endT, events, cursor, failures }, null, 2));
console.log(\`  recorded \${events.length} actions, \${failures.length} failed\`);
`;
}
